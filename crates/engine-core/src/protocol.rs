//! UI ↔ engine message protocol, shared by both editions.
//!
//! The TypeScript mirror in `packages/schema` is generated from these types
//! (`cargo test -p engine-core --features ts`); never hand-edit it.

#[cfg(feature = "serde")]
use serde::{Deserialize, Serialize};

/// UI → engine.
#[derive(Debug, Clone, Copy, PartialEq)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[cfg_attr(
    feature = "serde",
    serde(tag = "type", rename_all_fields = "camelCase")
)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub enum Command {
    Play,
    Stop,
    SetFrequency { hz: f32 },
    SetGain { gain: f32 },
}

/// Engine → UI.
#[derive(Debug, Clone, Copy, PartialEq)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[cfg_attr(
    feature = "serde",
    serde(tag = "type", rename_all_fields = "camelCase")
)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub enum Event {
    /// Absolute peak of the output since the previous `Peak` event.
    Peak { value: f32 },
}

/// Compact `(opcode, value)` encoding of [`Command`], used where commands cross a raw
/// boundary (the web edition's SharedArrayBuffer ring and the WASM ABI).
#[repr(u32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Opcode {
    Play = 0,
    Stop = 1,
    SetFrequency = 2,
    SetGain = 3,
}

impl Opcode {
    pub const ALL: [Opcode; 4] = [
        Opcode::Play,
        Opcode::Stop,
        Opcode::SetFrequency,
        Opcode::SetGain,
    ];

    pub fn name(self) -> &'static str {
        match self {
            Opcode::Play => "Play",
            Opcode::Stop => "Stop",
            Opcode::SetFrequency => "SetFrequency",
            Opcode::SetGain => "SetGain",
        }
    }
}

impl Command {
    pub fn to_raw(self) -> (u32, f32) {
        match self {
            Command::Play => (Opcode::Play as u32, 0.0),
            Command::Stop => (Opcode::Stop as u32, 0.0),
            Command::SetFrequency { hz } => (Opcode::SetFrequency as u32, hz),
            Command::SetGain { gain } => (Opcode::SetGain as u32, gain),
        }
    }

    pub fn from_raw(op: u32, value: f32) -> Option<Command> {
        Some(match op {
            x if x == Opcode::Play as u32 => Command::Play,
            x if x == Opcode::Stop as u32 => Command::Stop,
            x if x == Opcode::SetFrequency as u32 => Command::SetFrequency { hz: value },
            x if x == Opcode::SetGain as u32 => Command::SetGain { gain: value },
            _ => return None,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn raw_round_trip() {
        for cmd in [
            Command::Play,
            Command::Stop,
            Command::SetFrequency { hz: 440.0 },
            Command::SetGain { gain: 0.5 },
        ] {
            let (op, v) = cmd.to_raw();
            assert_eq!(Command::from_raw(op, v), Some(cmd));
        }
        assert_eq!(Command::from_raw(999, 0.0), None);
    }

    /// The JSON shape the desktop UI sends over Tauri IPC (see packages/schema `Command`).
    #[cfg(feature = "serde")]
    #[test]
    fn json_shape_matches_schema() {
        let cmd: Command = serde_json::from_str(r#"{"type":"SetFrequency","hz":220}"#).unwrap();
        assert_eq!(cmd, Command::SetFrequency { hz: 220.0 });
        let cmd: Command = serde_json::from_str(r#"{"type":"Play"}"#).unwrap();
        assert_eq!(cmd, Command::Play);
        let event = serde_json::to_string(&Event::Peak { value: 0.5 }).unwrap();
        assert_eq!(event, r#"{"type":"Peak","value":0.5}"#);
    }

    /// Writes the opcode table next to the ts-rs bindings so TypeScript never hardcodes it.
    #[cfg(feature = "ts")]
    #[test]
    fn export_opcodes() {
        let dir = std::path::PathBuf::from(
            std::env::var("TS_RS_EXPORT_DIR")
                .expect("TS_RS_EXPORT_DIR is set in .cargo/config.toml"),
        );
        let mut out = String::from(
            "// This file was generated by engine-core (protocol.rs). Do not edit this file manually.\n\n\
             export const Opcode = {\n",
        );
        for op in Opcode::ALL {
            out.push_str(&format!("  {}: {},\n", op.name(), op as u32));
        }
        out.push_str("} as const;\n\nexport type Opcode = (typeof Opcode)[keyof typeof Opcode];\n");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("Opcode.ts"), out).unwrap();
    }
}
